// Command gen writes the MCP tool definitions from tools.json.
//
// The tool set is data: each entry names the plug-in command to forward to,
// the arguments it accepts and the documentation shown to the model. Keeping
// it in JSON means adding a tool is a data change, and that the argument
// structs, their defaults and the registration calls cannot drift apart.
//
// Run it with `make generate`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"

	_ "embed"
	"encoding/json"
)

//go:embed tools.json
var toolsJSON []byte

// spec is the whole tool table.
type spec struct {
	Tools []tool `json:"tools"`
}

// tool is one MCP tool.
type tool struct {
	Name        string  `json:"name"`
	Struct      string  `json:"struct"`
	Command     string  `json:"command"`
	Kind        string  `json:"kind"`
	Description string  `json:"description"`
	Params      []param `json:"params"`
}

// param is one tool argument.
type param struct {
	Name        string `json:"name"`
	Field       string `json:"field"`
	GoType      string `json:"goType"`
	Description string `json:"description"`
	// Default is a Go expression assigned when the caller omits the
	// argument, or empty when the zero value is already correct.
	Default  string `json:"default"`
	Required bool   `json:"required"`
}

// required lists the arguments a caller must supply.
func (t tool) required() []string {
	var out []string

	for _, p := range t.Params {
		if p.Required {
			out = append(out, p.Name)
		}
	}

	return out
}

// defaults lists the arguments that need an explicit default.
func (t tool) defaults() []param {
	var out []param

	for _, p := range t.Params {
		if p.Default != "" {
			out = append(out, p)
		}
	}

	return out
}

func main() {
	out := flag.String("out", "internal/server/tools_gen.go", "file to write")
	flag.Parse()

	var s spec
	if err := json.Unmarshal(toolsJSON, &s); err != nil {
		log.Fatalf("gen: parse tools.json: %v", err)
	}

	src, err := render(s)
	if err != nil {
		log.Fatalf("gen: %v", err)
	}

	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // source file
		log.Fatalf("gen: write %s: %v", *out, err)
	}

	fmt.Printf("gen: wrote %d tools to %s\n", len(s.Tools), *out)
}

// render produces the formatted Go source.
func render(s spec) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("// Code generated by internal/gen from tools.json. DO NOT EDIT.\n\n")
	b.WriteString("package server\n\n")

	for _, t := range s.Tools {
		writeStruct(&b, t)
		writeDefaults(&b, t)
	}

	writeRegistration(&b, s)
	writeDescriptions(&b, s)

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}

	return src, nil
}

// writeStruct emits a tool's argument struct.
//
// No field is tagged omitempty: the plug-in distinguishes an explicit null
// from an absent key, so every argument goes on the wire. The required set is
// narrowed on the schema instead, in schemaFor.
func writeStruct(b *bytes.Buffer, t tool) {
	fmt.Fprintf(b, "// %s holds the arguments for the %s tool.\n", t.Struct, t.Name)

	if len(t.Params) == 0 {
		fmt.Fprintf(b, "type %s struct{}\n\n", t.Struct)

		return
	}

	fmt.Fprintf(b, "type %s struct {\n", t.Struct)

	for _, p := range t.Params {
		fmt.Fprintf(b, "\t%s %s `json:%s", p.Field, p.GoType, strconv.Quote(p.Name))

		if p.Description != "" {
			fmt.Fprintf(b, " jsonschema:%s", strconv.Quote(p.Description))
		}

		b.WriteString("`\n")
	}

	b.WriteString("}\n\n")
}

// writeDefaults emits SetDefaults for tools with non-zero defaults.
func writeDefaults(b *bytes.Buffer, t tool) {
	defaults := t.defaults()
	if len(defaults) == 0 {
		return
	}

	fmt.Fprintf(b, "// SetDefaults applies the defaults documented for the %s tool.\n", t.Name)
	fmt.Fprintf(b, "func (in *%s) SetDefaults() {\n", t.Struct)

	for _, p := range defaults {
		fmt.Fprintf(b, "\tif in.%s == nil {\n\t\tin.%s = %s\n\t}\n", p.Field, p.Field, p.Default)
	}

	b.WriteString("}\n\n")
}

// writeRegistration emits the call that wires the pass-through tools up.
func writeRegistration(b *bytes.Buffer, s spec) {
	b.WriteString("// registerGenerated wires up every tool that forwards its arguments to the\n")
	b.WriteString("// plug-in unchanged and returns the plug-in's results verbatim.\n")
	b.WriteString("func registerGenerated(r *registrar) {\n")

	count := 0

	for _, t := range s.Tools {
		if t.Kind == "handwritten" {
			continue
		}

		count++

		adder := "addObject"
		if t.Kind == "image" {
			adder = "addImage"
		}

		fmt.Fprintf(b, "\t%s[%s](r, toolDef{\n", adder, t.Struct)
		fmt.Fprintf(b, "\t\tName: %s,\n", strconv.Quote(t.Name))
		fmt.Fprintf(b, "\t\tCommand: %s,\n", strconv.Quote(t.Command))
		fmt.Fprintf(b, "\t\tRequired: %s,\n", goStrings(t.required()))
		fmt.Fprintf(b, "\t\tDescription: %s,\n", strconv.Quote(t.Description))
		b.WriteString("\t})\n")
	}

	b.WriteString("}\n\n")
	b.WriteString("// generatedToolCount is how many tools registerGenerated adds.\n")
	fmt.Fprintf(b, "const generatedToolCount = %d\n\n", count)
}

// writeDescriptions emits documentation constants for the hand-written tools
// so all tool documentation stays in one place.
func writeDescriptions(b *bytes.Buffer, s spec) {
	b.WriteString("// Descriptions for the tools registered by hand in handwritten.go.\n")
	b.WriteString("const (\n")

	for _, t := range s.Tools {
		if t.Kind != "handwritten" {
			continue
		}

		fmt.Fprintf(b, "\t%sDesc = %s\n\n", lowerFirst(strings.ReplaceAll(t.Struct, "Input", "")),
			strconv.Quote(t.Description))
	}

	b.WriteString(")\n")
}

// goStrings renders a string slice literal, or nil when empty.
func goStrings(values []string) string {
	if len(values) == 0 {
		return "nil"
	}

	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}

	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// lowerFirst lowercases the leading run of capitals so CallAPI becomes callAPI.
func lowerFirst(s string) string {
	if s == "" {
		return s
	}

	runes := []rune(s)
	for i, r := range runes {
		if r >= 'a' && r <= 'z' {
			// Keep the last capital as the start of the next word.
			if i > 1 {
				i--
			}

			for j := range i {
				runes[j] += 'a' - 'A'
			}

			return string(runes)
		}
	}

	return strings.ToLower(s)
}
